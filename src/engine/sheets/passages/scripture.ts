/**
 * One curated entry: a contiguous run of verses in one chapter.
 *
 * Contiguous and single-chapter on purpose. A set that skips about — the
 * Romans Road, say — is several entries in one collection rather than one entry
 * with holes in it, which keeps `first + verses.length - 1` a true statement of
 * what was quoted and keeps the release check a straight line-by-line compare.
 */
export type ScriptureEntry = {
  id: string;
  /** How it is named on a sheet. "Psalm 23", "1 Corinthians 13:4-8". */
  ref: string;
  /** eBible's own three-letter book code, so a verse can be found again. */
  book: string;
  chapter: number;
  /** The verse `verses[0]` is. The last is `first + verses.length - 1`. */
  first: number;
  collection: string;
  /** One string per verse, in order, exactly as the release has it. */
  verses: readonly string[];
};

