/**
 * The memory-verse and passage library, in the World English Bible Updated.
 *
 * ── Source ──────────────────────────────────────────────────────────────────
 *   Translation   World English Bible Updated (WEBu) — the classic WEB with
 *                 "LORD" / "GOD" in place of "Yahweh", and American spelling.
 *   Publisher     eBible.org · https://ebible.org/engwebu/ · worldenglish.bible
 *   Release       engwebu, source files dated 15 August 2026
 *   Format        the verse-per-line release, `engwebu_vpl.txt`, which is
 *                 eBible's own text-only edition: no notes, no section
 *                 headings, no paragraph marks, one verse to a line.
 *   Pulled        17 August 2026
 *   Licence       Public domain. "World English Bible" is a trademark of
 *                 eBible.org and the single condition attached is that a
 *                 *modified* text must not carry the name.
 *
 * `scripture.test.ts` holds that condition to a build. Every verse below is
 * checked, character for character, against `release/engwebu.vpl.txt` — the
 * lines of the release this library quotes, saved exactly as they were
 * downloaded. Edit a verse here and the suite fails; that is the whole design.
 * `npm run scripture:pull` re-fetches the current release and rewrites that
 * file, which is how eBible's request that publishers carry recent typo
 * corrections becomes a command rather than a promise.
 *
 * ── What "verbatim" rules out ───────────────────────────────────────────────
 * Smart quotes are not applied, lines are not re-wrapped, and case is not
 * changed. The release already uses curly quotation marks and apostrophes, so
 * those are *kept*, not added — the rule is that nothing is transformed, in
 * either direction. Where a psalm carries a superscription ("A Psalm by
 * David."), the release puts it at the head of verse 1 and so does this file:
 * it is text, not a heading, and dropping it would be an edit.
 *
 * Verse numbers are absent, which the condition allows: they are apparatus
 * rather than text, and a child copying "1" before every clause is copying
 * typography. The reference is on the entry, and a sheet prints it once.
 *
 * ── What is here, and what deliberately isn't ───────────────────────────────
 * A few hundred memory verses and short passages — the ones copywork actually
 * uses — and not a Bible. The whole WEBu is about five megabytes. The 274
 * entries below are 52KB of text (54KB for the KJV beside them, 37KB for the
 * pair once gzipped), which is the "tens of kilobytes, not megabytes" §12 asks
 * for, and `scripture.test.ts` keeps a ceiling on it so the next hundred verses
 * added are a decision rather than a drift. Anything outside the set is
 * PRINT19's paste-your-own, or one day per-book JSON fetched on demand.
 *
 * Collections are cut by *book*, not by theme, for the reason in types.ts: a
 * theme is an editorial claim about a verse and a book is a fact about it.
 */
